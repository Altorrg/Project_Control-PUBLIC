begin;

-- Az eddigi elutasitas/szundi rekordokon taroljuk az egyeni prioritast is.
alter table public.notification_dismissals
    add column if not exists priority smallint not null default 2;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conrelid = 'public.notification_dismissals'::regclass
          and conname = 'notification_dismissals_priority_check'
    ) then
        alter table public.notification_dismissals
            add constraint notification_dismissals_priority_check
            check (priority between 1 and 4);
    end if;
end;
$$;

create table if not exists public.notification_tasks (
    id bigint generated by default as identity primary key,
    profile_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
    project_id bigint references public.projects(id) on delete set null,
    title text not null check (char_length(btrim(title)) between 1 and 255),
    details text not null default '' check (char_length(details) <= 5000),
    due_date date not null,
    due_time time,
    priority smallint not null default 2 check (priority between 1 and 4),
    target_module text check (
        target_module is null or target_module in (
            'settings', 'disciplines', 'schedule', 'subcontractors',
            'finance', 'engagements', 'admin'
        )
    ),
    completed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists notification_tasks_today_idx
    on public.notification_tasks(profile_id, due_date, completed_at, priority);

alter table public.notification_tasks enable row level security;

drop policy if exists notification_tasks_own on public.notification_tasks;
create policy notification_tasks_own on public.notification_tasks
for all to authenticated
using (
    profile_id = auth.uid()
    and (project_id is null or public.can_access_project(project_id, false))
)
with check (
    profile_id = auth.uid()
    and (project_id is null or public.can_access_project(project_id, false))
);

grant select, insert, update, delete on public.notification_tasks to authenticated;

do $$
declare sequence_name text;
begin
    select pg_get_serial_sequence('public.notification_tasks', 'id') into sequence_name;
    if sequence_name is not null then
        execute format('grant usage, select on sequence %s to authenticated', sequence_name);
    end if;
end;
$$;

-- Pontos idopontig tarto halasztas es az egyeni prioritas egyetlen auditálhato RPC-ben.
create or replace function public.notification_action(
    target_alert_key text,
    action_name text,
    remind_at timestamptz default null,
    priority_value integer default null
)
returns public.notification_dismissals
language plpgsql
security definer
set search_path = ''
as $$
declare
    result public.notification_dismissals;
    target_time timestamptz;
begin
    if auth.uid() is null then
        raise exception 'authentication required';
    end if;
    if nullif(btrim(target_alert_key), '') is null then
        raise exception 'alert key required';
    end if;
    if priority_value is not null and priority_value not between 1 and 4 then
        raise exception 'priority must be between 1 and 4';
    end if;

    if action_name = 'priority' then
        if priority_value is null then
            raise exception 'priority required';
        end if;
        insert into public.notification_dismissals(
            profile_id, alert_key, dismissed_at, snooze_until, dismiss_mode, priority
        ) values (
            auth.uid(), target_alert_key, now(), null, 'snooze', priority_value
        )
        on conflict (profile_id, alert_key) do update set
            priority = excluded.priority
        returning * into result;
        return result;
    end if;

    if action_name = 'forever' then
        target_time := null;
    elsif action_name = 'skip_15' then
        target_time := now() + interval '15 minutes';
    elsif action_name = 'defer_24' then
        target_time := now() + interval '24 hours';
    elsif action_name = 'custom' then
        if remind_at is null or remind_at <= now() then
            raise exception 'future reminder time required';
        end if;
        target_time := remind_at;
    else
        raise exception 'invalid notification action';
    end if;

    insert into public.notification_dismissals as existing(
        profile_id, alert_key, dismissed_at, snooze_until, dismiss_mode, priority
    ) values (
        auth.uid(), target_alert_key, now(), target_time,
        case when action_name = 'forever' then 'forever' else 'snooze' end,
        coalesce(priority_value, 2)
    )
    on conflict (profile_id, alert_key) do update set
        dismissed_at = excluded.dismissed_at,
        snooze_until = excluded.snooze_until,
        dismiss_mode = excluded.dismiss_mode,
        priority = coalesce(priority_value, existing.priority)
    returning * into result;
    return result;
end;
$$;

revoke all on function public.notification_action(text, text, timestamptz, integer) from public, anon;
grant execute on function public.notification_action(text, text, timestamptz, integer) to authenticated;

-- A korabbi 10/25 napos szabalyokat megtartjuk, es a hianyzo elozo havi
-- szakagi munkaido-bejegyzeseket projektenkent, szakagankent jelezzuk.
create or replace function public.current_notifications()
returns setof jsonb
language sql
stable
security definer
set search_path = ''
as $$
    with today_value as (
        select public.app_today() value
    ),
    month_values as (
        select
            value,
            (date_trunc('month', value)::date - interval '1 month')::date previous_month,
            date_trunc('month', value)::date current_month
        from today_value
    ),
    project_quality as (
        select
            p.id,
            p.name,
            m.value,
            not exists (
                select 1 from public.project_daily_rates rate
                where rate.project_id = p.id
                  and rate.year = extract(year from m.value)::integer
            ) missing_daily_rate,
            not exists (
                select 1 from public.project_contract_sections section
                where section.project_id = p.id
            ) missing_contract_section,
            exists (
                select 1 from public.project_contract_sections section
                where section.project_id = p.id
            ) and not exists (
                select 1 from public.project_milestones milestone
                where milestone.project_id = p.id
            ) missing_milestone
        from public.projects p
        cross join month_values m
        where not p.is_deleted
          and public.can_access_project(p.id, false)
    ),
    candidates as (
        select
            'monthly:timesheet:' || p.id || ':' || d.id || ':' || to_char(m.previous_month, 'YYYY-MM') alert_key,
            p.id project_id,
            p.name project_name,
            d.name || ' - előző havi munkaidő' subject,
            'A(z) ' || to_char(m.previous_month, 'YYYY. MM.') || ' havi munkaidő még nincs rögzítve.' message,
            'monthly' alert_type,
            'disciplines' target_module,
            d.id target_id,
            m.value due_date,
            1::smallint default_priority
        from public.projects p
        join public.project_disciplines d on d.project_id = p.id and d.visible
        cross join month_values m
        where not p.is_deleted
          and extract(day from m.value) <= 5
          and public.can_access_project(p.id, false)
          and not exists (
              select 1
              from public.daily_progress progress
              where progress.project_id = p.id
                and progress.discipline_name = d.name
                and progress.record_date >= m.previous_month
                and progress.record_date < m.current_month
          )

        union all

        select
            'quality:project:' || quality.id || ':' || extract(year from quality.value)::integer || ':' ||
                quality.missing_daily_rate::integer || quality.missing_contract_section::integer || quality.missing_milestone::integer,
            quality.id,
            quality.name,
            'Projektadatok kiegészítése',
            concat_ws(' ',
                case when quality.missing_daily_rate then 'Nincs aktuális éves napidíj beállítva.' end,
                case when quality.missing_contract_section then 'Nincs főszerződéses pénzügyi fázis rögzítve.' end,
                case when quality.missing_milestone then 'A pénzügyi fázisokhoz nincs pénzügyi mérföldkő.' end
            ),
            'quality',
            'settings',
            null::bigint,
            quality.value,
            case when quality.missing_daily_rate or quality.missing_contract_section then 1 else 2 end::smallint
        from project_quality quality
        where quality.missing_daily_rate or quality.missing_contract_section or quality.missing_milestone

        union all

        select
            'quality:subcontractor-mapping:' || p.id || ':' || count(*) || ':' || max(w.id),
            p.id,
            p.name,
            'Hiányzó pénzügyi összerendelés',
            count(*) || ' elfogadott alvállalkozói szerződés nincs belső szakághoz rendelve.',
            'quality',
            'finance',
            null::bigint,
            m.value,
            2::smallint
        from public.subcontractor_workflows w
        join public.projects p on p.id = w.project_id
        cross join month_values m
        where not w.is_deleted
          and w.acceptance = 'Elfogadva'
          and public.can_access_project(w.project_id, false)
          and not exists (
              select 1 from public.finance_mappings mapping
              where mapping.project_id = w.project_id and mapping.workflow_id = w.id
          )
        group by p.id, p.name, m.value

        union all

        select
            'review:schedule-row:' || p.id || ':' || count(*) || ':' || max(review.id),
            p.id,
            p.name,
            'Ütemtervi besorolás ellenőrzése',
            count(*) || ' régi ütemtervi elem pénzügyi fázisát kell ellenőrizni.',
            'review',
            'schedule',
            null::bigint,
            m.value,
            2::smallint
        from public.schedule_rows_financial_phase_review review
        join public.projects p on p.id = review.project_id
        cross join month_values m
        where public.can_access_project(review.project_id, false)
        group by p.id, p.name, m.value

        union all

        select
            'review:subcontractor-key:' || p.id || ':' || count(*) || ':' || max(review.workflow_id),
            p.id,
            p.name,
            'Alvállalkozói tervezési mérföldkövek ellenőrzése',
            count(*) || ' alvállalkozói folyamat tervezési mérföldkő-hozzárendelését kell ellenőrizni.',
            'review',
            'subcontractors',
            null::bigint,
            m.value,
            2::smallint
        from public.subcontractor_workflow_schedule_key_review review
        join public.projects p on p.id = review.project_id
        cross join month_values m
        where public.can_access_project(review.project_id, false)
        group by p.id, p.name, m.value

        union all

        select
            'sub:' || w.id || ':' || to_char(w.updated_at, 'YYYYMMDDHH24MISS'),
            w.project_id,
            p.name,
            w.company_name,
            (m.value - w.updated_at::date) || ' napja áll az alvállalkozói folyamat',
            'sub',
            'subcontractors',
            w.id,
            m.value,
            2::smallint
        from public.subcontractor_workflows w
        join public.projects p on p.id = w.project_id
        cross join month_values m
        where not w.is_deleted
          and w.signature_status <> 'Aláírva'
          and public.can_access_project(w.project_id, false)
          and extract(day from m.value) <= 5
          and m.value - w.updated_at::date >= 10

        union all

        select
            'eng:' || a.id || ':' || to_char(coalesce(a.last_date, a.updated_at::date), 'YYYYMMDD'),
            a.project_id,
            p.name,
            coalesce(ep.name, d.name),
            'Engedélyezés: ' || (m.value - coalesce(a.last_date, a.updated_at::date)) ||
                ' napja nincs előrelépés. ' || et.name || ' | ' || s.code || ' - ' || s.name,
            'eng',
            'engagements',
            a.id,
            m.value,
            1::smallint
        from public.eng_assignments a
        join public.projects p on p.id = a.project_id
        join public.eng_disciplines d on d.id = a.discipline_id
        join public.eng_tasks et on et.id = a.task_id
        join public.eng_statuses s on s.code = a.status_code
        left join public.eng_partners ep on ep.id = a.partner_id
        cross join month_values m
        where not a.is_deleted
          and not s.is_closed
          and public.can_access_project(a.project_id, false)
          and m.value - coalesce(a.last_date, a.updated_at::date) >= 25
    )
    select jsonb_build_object(
        'alert_key', c.alert_key,
        'project_id', c.project_id,
        'project_name', c.project_name,
        'subject', c.subject,
        'message', c.message,
        'alert_type', c.alert_type,
        'target_module', c.target_module,
        'target_id', c.target_id,
        'due_date', c.due_date,
        'priority', coalesce(d.priority, c.default_priority)
    )
    from candidates c
    left join public.notification_dismissals d
      on d.profile_id = auth.uid() and d.alert_key = c.alert_key
    where d.alert_key is null or (
        d.dismiss_mode <> 'forever'
        and (d.snooze_until is null or d.snooze_until <= now())
    )
    order by coalesce(d.priority, c.default_priority), c.project_name, c.alert_type, c.subject;
$$;

revoke all on function public.current_notifications() from public, anon;
grant execute on function public.current_notifications() to authenticated;

notify pgrst, 'reload schema';

commit;

