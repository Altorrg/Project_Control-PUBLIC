begin;

create table if not exists public.project_offer_request_settings (
    project_id bigint primary key references public.projects(id) on delete cascade,
    history text not null default '' check (char_length(history) <= 5000),
    task_description text not null default '' check (char_length(task_description) <= 5000),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.project_company_contacts (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.projects(id) on delete cascade,
    name text not null check (char_length(name) between 1 and 255),
    job_title text not null default '' check (char_length(job_title) <= 255),
    email text not null default '' check (char_length(email) <= 255),
    phone text not null default '' check (char_length(phone) <= 255),
    display_order integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists project_company_contacts_project_order_idx
    on public.project_company_contacts(project_id, display_order, name, id);

alter table public.project_offer_request_settings enable row level security;
alter table public.project_company_contacts enable row level security;

grant select, insert, update, delete on table
    public.project_offer_request_settings,
    public.project_company_contacts
to authenticated;

revoke all on table
    public.project_offer_request_settings,
    public.project_company_contacts
from anon;

do $contact_sequence_grants$
declare
    identity_sequence regclass;
begin
    identity_sequence := pg_get_serial_sequence(
        'public.project_company_contacts',
        'id'
    )::regclass;
    if identity_sequence is not null then
        execute format(
            'grant usage, select on sequence %s to authenticated',
            identity_sequence
        );
        execute format(
            'revoke all on sequence %s from anon',
            identity_sequence
        );
    end if;
end;
$contact_sequence_grants$;

drop policy if exists project_offer_request_settings_read on public.project_offer_request_settings;
create policy project_offer_request_settings_read
    on public.project_offer_request_settings for select to authenticated
    using (public.can_access_project(project_id, false));

drop policy if exists project_offer_request_settings_write on public.project_offer_request_settings;
create policy project_offer_request_settings_write
    on public.project_offer_request_settings for all to authenticated
    using (public.can_access_project(project_id, true))
    with check (public.can_access_project(project_id, true));

drop policy if exists project_company_contacts_read on public.project_company_contacts;
create policy project_company_contacts_read
    on public.project_company_contacts for select to authenticated
    using (public.can_access_project(project_id, false));

drop policy if exists project_company_contacts_write on public.project_company_contacts;
create policy project_company_contacts_write
    on public.project_company_contacts for all to authenticated
    using (public.can_access_project(project_id, true))
    with check (public.can_access_project(project_id, true));

drop trigger if exists set_updated_at on public.project_offer_request_settings;
create trigger set_updated_at before update on public.project_offer_request_settings
    for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at on public.project_company_contacts;
create trigger set_updated_at before update on public.project_company_contacts
    for each row execute function public.set_updated_at();

drop trigger if exists audit_changes on public.project_offer_request_settings;
create trigger audit_changes after insert or update or delete on public.project_offer_request_settings
    for each row execute function public.write_audit_log();

drop trigger if exists audit_changes on public.project_company_contacts;
create trigger audit_changes after insert or update or delete on public.project_company_contacts
    for each row execute function public.write_audit_log();

commit;
