create or replace function public.replace_subcontractor_workflow_schedule_keys(target_project_id bigint, target_workflow_id bigint, requested_assignments jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare invalid_count integer;
begin
    if not public.can_access_project(target_project_id, true) or not public.has_permission('subcontractor_write') then raise exception 'permission denied'; end if;
    if jsonb_typeof(coalesce(requested_assignments, '[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(requested_assignments, '[]'::jsonb)) > 100 then raise exception 'invalid assignment payload'; end if;
    if not exists (select 1 from public.subcontractor_workflows workflow where workflow.id = target_workflow_id and workflow.project_id = target_project_id and not workflow.is_deleted) then raise exception 'workflow not found'; end if;
    with requested as (
        select distinct (item.value ->> 'financial_phase_no')::integer as financial_phase_no, (item.value ->> 'schedule_key_id')::bigint as schedule_key_id
        from jsonb_array_elements(coalesce(requested_assignments, '[]'::jsonb)) as item(value)
    )
    select count(*) into invalid_count from requested request
    left join public.project_contract_sections contract_section on contract_section.project_id = target_project_id and contract_section.section_no = request.financial_phase_no
    left join public.schedule_keys schedule_key on schedule_key.id = request.schedule_key_id
    where request.financial_phase_no not between 0 and 5 or request.schedule_key_id is null or contract_section.id is null or schedule_key.id is null;
    if invalid_count > 0 then raise exception 'unknown financial phase or schedule key'; end if;
    delete from public.subcontractor_workflow_schedule_keys where project_id = target_project_id and workflow_id = target_workflow_id;
    insert into public.subcontractor_workflow_schedule_keys(project_id, workflow_id, financial_phase_no, schedule_key_id)
    select target_project_id, target_workflow_id, (item.value ->> 'financial_phase_no')::integer, (item.value ->> 'schedule_key_id')::bigint
    from (select distinct item.value from jsonb_array_elements(coalesce(requested_assignments, '[]'::jsonb)) as item(value)) item;
end;
$$;
grant execute on function public.replace_subcontractor_workflow_schedule_keys(bigint, bigint, jsonb) to authenticated;
revoke all on function public.replace_subcontractor_workflow_schedule_keys(bigint, bigint, jsonb) from anon;

create or replace view public.subcontractor_workflow_schedule_key_review
with (security_invoker = true) as
select workflow.id as workflow_id, workflow.project_id, workflow.company_name, workflow.code,
       workflow.legacy_payload -> 'schedule_keys' as legacy_schedule_keys,
       'Régi jelkulcs-hozzárendelés kézi ellenőrzése szükséges' as review_reason
from public.subcontractor_workflows workflow
where workflow.legacy_payload ? 'schedule_keys'
  and not exists (select 1 from public.subcontractor_workflow_schedule_keys assignment where assignment.workflow_id = workflow.id);
grant select on public.subcontractor_workflow_schedule_key_review to authenticated;
revoke all on public.subcontractor_workflow_schedule_key_review from anon;

create or replace function public.current_actionable_gaps()
returns table (gap_key text, priority integer, project_id bigint, project_name text, message text, relevant_date date, source_module text, target_module text)
language sql stable security definer set search_path = '' as $$
    with visible_projects as (
        select project.id, project.name from public.projects project where not project.is_deleted and public.can_access_project(project.id, false)
    ), candidates (gap_key, priority, project_id, project_name, message, relevant_date, source_module, target_module) as (
        select 'quality:daily-rate:' || project.id || ':' || extract(year from public.app_today())::text, 1, project.id, project.name, 'Nincs aktuális évi napidíj beállítva.', null::date, 'Adatminőség', 'settings'
        from visible_projects project where not exists (select 1 from public.project_daily_rates rate where rate.project_id = project.id and rate.year = extract(year from public.app_today())::integer)
        union all select 'quality:contract-section:' || project.id, 1, project.id, project.name, 'Nincs főszerződéses pénzügyi fázis rögzítve.', null::date, 'Adatminőség', 'settings'
        from visible_projects project where not exists (select 1 from public.project_contract_sections contract_section where contract_section.project_id = project.id)
        union all select 'quality:milestone:' || project.id, 2, project.id, project.name, 'A főszerződéses pénzügyi fázisokhoz nincs szerződéses mérföldkő.', null::date, 'Adatminőség', 'settings'
        from visible_projects project where exists (select 1 from public.project_contract_sections contract_section where contract_section.project_id = project.id) and not exists (select 1 from public.project_milestones milestone where milestone.project_id = project.id)
        union all select 'quality:subcontractor-mapping:' || workflow.id, 2, project.id, project.name, 'Alvállalkozói szerződés nincs belső szakághoz rendelve: ' || workflow.company_name, null::date, 'Pénzügy', 'finance'
        from public.subcontractor_workflows workflow join visible_projects project on project.id = workflow.project_id where not workflow.is_deleted and workflow.acceptance = 'Elfogadva' and not exists (select 1 from public.finance_mappings mapping where mapping.project_id = workflow.project_id and mapping.workflow_id = workflow.id)
        union all select 'review:schedule-row:' || review.id, 2, project.id, project.name, review.review_reason, null::date, 'Ütemterv', 'schedules'
        from public.schedule_rows_financial_phase_review review join visible_projects project on project.id = review.project_id
        union all select 'review:subcontractor-key:' || review.workflow_id, 2, project.id, project.name, review.review_reason || ': ' || review.company_name, null::date, 'Alvállalkozók', 'subcontractors'
        from public.subcontractor_workflow_schedule_key_review review join visible_projects project on project.id = review.project_id
        union all select notification.payload ->> 'alert_key', 2, (notification.payload ->> 'project_id')::bigint, notification.payload ->> 'project_name', notification.payload ->> 'message', null::date,
                         case notification.payload ->> 'alert_type' when 'eng' then 'Engedélyek' when 'sub' then 'Alvállalkozók' else 'Értesítések' end,
                         case notification.payload ->> 'alert_type' when 'eng' then 'engagements' when 'sub' then 'subcontractors' else 'disciplines' end
        from public.current_notifications() as notification(payload)
        where (notification.payload ->> 'project_id')::bigint = 0 or exists (select 1 from visible_projects project where project.id = (notification.payload ->> 'project_id')::bigint)
    )
    select distinct on (gap_key) gap_key, priority, project_id, project_name, message, relevant_date, source_module, target_module
    from candidates order by gap_key, priority asc, relevant_date asc nulls last;
$$;
grant execute on function public.current_actionable_gaps() to authenticated;
revoke all on function public.current_actionable_gaps() from anon;

