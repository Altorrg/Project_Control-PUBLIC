alter table public.schedule_rows
    add column if not exists section text,
    add column if not exists phase_code text,
    add column if not exists financial_phase_no integer,
    add column if not exists schedule_key_id bigint;

-- Egyes régi adatbázisok a jelkulcsot még a phase mezőben tárolják.
do $legacy_phase_code$
begin
    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'schedule_rows'
          and column_name = 'phase'
    ) then
        execute $sql$
            update public.schedule_rows
            set phase_code = phase
            where phase_code is null
              and nullif(btrim(phase), '') is not null
        $sql$;
    end if;
end;
$legacy_phase_code$;
do $schedule_constraints$
begin
    if not exists (select 1 from pg_constraint where conrelid = 'public.schedule_rows'::regclass and conname = 'schedule_rows_financial_phase_no_check') then
        alter table public.schedule_rows add constraint schedule_rows_financial_phase_no_check check (financial_phase_no between 0 and 5);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'public.schedule_rows'::regclass and conname = 'schedule_rows_project_financial_phase_fkey') then
        alter table public.schedule_rows add constraint schedule_rows_project_financial_phase_fkey
            foreign key (project_id, financial_phase_no) references public.project_contract_sections(project_id, section_no) on delete restrict;
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'public.schedule_rows'::regclass and conname = 'schedule_rows_schedule_key_id_fkey') then
        alter table public.schedule_rows add constraint schedule_rows_schedule_key_id_fkey
            foreign key (schedule_key_id) references public.schedule_keys(id) on delete restrict;
    end if;
end;
$schedule_constraints$;
create index if not exists schedule_rows_project_financial_phase_position_idx on public.schedule_rows(project_id, financial_phase_no, position, id);
create index if not exists schedule_rows_schedule_key_idx on public.schedule_rows(schedule_key_id);

-- Csak egyértelmű régi érték kerül automatikusan hozzárendelésre.
with explicit_assignment as (
    select row.id, contract_section.section_no
    from public.schedule_rows row
    join public.project_contract_sections contract_section
      on contract_section.project_id = row.project_id
     and btrim(coalesce(row.section, '')) ~ '^[0-5]$'
     and contract_section.section_no = btrim(row.section)::integer
    where row.financial_phase_no is null
), single_phase_assignment as (
    select row.id, contract_section.section_no
    from public.schedule_rows row
    join (select project_id, min(section_no) as section_no from public.project_contract_sections group by project_id having count(*) = 1) contract_section
      on contract_section.project_id = row.project_id
    where row.financial_phase_no is null and btrim(coalesce(row.section, '')) = ''
), assignments as (
    select * from explicit_assignment union all select * from single_phase_assignment
)
update public.schedule_rows row set financial_phase_no = assignment.section_no
from assignments assignment where row.id = assignment.id and row.financial_phase_no is null;

update public.schedule_rows row set schedule_key_id = schedule_key.id
from public.schedule_keys schedule_key
where row.schedule_key_id is null
  and btrim(coalesce(row.phase_code, '')) <> ''
  and schedule_key.code_key = lower(btrim(row.phase_code));

create or replace view public.schedule_rows_financial_phase_review
with (security_invoker = true) as
select row.id, row.project_id, row.position, row.section, row.phase_code, row.phase_name,
       row.financial_phase_no, row.schedule_key_id,
       case
           when row.financial_phase_no is null and exists (select 1 from public.project_contract_sections contract_section where contract_section.project_id = row.project_id)
             then 'Pénzügyi fázis kézi ellenőrzése szükséges'
           when row.schedule_key_id is null and btrim(coalesce(row.phase_code, '')) <> ''
             then 'Jelkulcs kézi ellenőrzése szükséges'
           else 'Ellenőrzendő'
       end as review_reason
from public.schedule_rows row
where row.financial_phase_no is null or (row.schedule_key_id is null and btrim(coalesce(row.phase_code, '')) <> '');
grant select on public.schedule_rows_financial_phase_review to authenticated;
revoke all on public.schedule_rows_financial_phase_review from anon;

