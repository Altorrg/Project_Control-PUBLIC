create table if not exists public.schedule_keys (
    id bigint generated by default as identity primary key,
    code text not null check (char_length(btrim(code)) between 1 and 255),
    code_key text generated always as (lower(btrim(code))) stored unique,
    description text not null default '' check (char_length(description) <= 5000),
    start_event text not null default '' check (char_length(start_event) <= 1000),
    end_event text not null default '' check (char_length(end_event) <= 1000),
    note text not null default '' check (char_length(note) <= 5000),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists schedule_keys_active_code_idx on public.schedule_keys(is_active, code, id);
alter table public.schedule_keys enable row level security;
grant select, insert, update, delete on public.schedule_keys to authenticated;
revoke all on public.schedule_keys from anon;
do $sequence_grants$
declare sequence_name regclass;
begin
    sequence_name := pg_get_serial_sequence('public.schedule_keys', 'id')::regclass;
    if sequence_name is not null then
        execute format('grant usage, select on sequence %s to authenticated', sequence_name);
        execute format('revoke all on sequence %s from anon', sequence_name);
    end if;
end;
$sequence_grants$;
