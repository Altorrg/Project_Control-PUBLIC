create or replace function public.validate_subcontractor_workflow_schedule_key()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
    if not exists (select 1 from public.subcontractor_workflows workflow where workflow.id = new.workflow_id and workflow.project_id = new.project_id and not workflow.is_deleted) then
        raise exception 'workflow does not belong to project';
    end if;
    return new;
end;
$$;
drop trigger if exists validate_project_workflow on public.subcontractor_workflow_schedule_keys;
create trigger validate_project_workflow before insert or update on public.subcontractor_workflow_schedule_keys for each row execute function public.validate_subcontractor_workflow_schedule_key();
