create extension if not exists pg_trgm;
create extension if not exists pgcrypto;

create table if not exists public.profiles (
    id uuid primary key default gen_random_uuid(),
    display_name text not null check (char_length(display_name) between 1 and 255),
    role text not null default 'editor' check (role in ('admin', 'editor')),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.profiles drop constraint if exists profiles_id_fkey;

create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(name) between 1 and 255),
    work_number text not null default '',
    responsible_company text not null default '',
    contract_subject text not null default '',
    creation_idempotency_key text check (
        creation_idempotency_key is null
        or char_length(creation_idempotency_key) between 1 and 255
    ),
    creation_request_fingerprint text check (
        creation_request_fingerprint is null
        or creation_request_fingerprint ~ '^[0-9a-f]{64}$'
    ),
    contract_value numeric(18,2) check (contract_value is null or contract_value >= 0),
    customer text not null default '',
    main_customer text not null default '',
    status text not null default 'Aktív',
    created_by uuid references public.profiles(id) on delete set null default auth.uid(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    is_deleted boolean not null default false
);

alter table public.projects
    add column if not exists work_number text not null default '',
    add column if not exists responsible_company text not null default '',
    add column if not exists contract_subject text not null default '',
    add column if not exists creation_idempotency_key text,
    add column if not exists creation_request_fingerprint text;

create unique index if not exists projects_creator_idempotency_key_uidx
