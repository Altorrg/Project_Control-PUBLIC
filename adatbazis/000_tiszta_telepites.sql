        union all select 'quality:subcontractor-mapping:' || workflow.id, 2, project.id, project.name, 'Alvállalkozói szerződés nincs belső szakághoz rendelve: ' || workflow.company_name, null::date, 'Pénzügy', 'finance'
        from public.subcontractor_workflows workflow join visible_projects project on project.id = workflow.project_id where not workflow.is_deleted and workflow.acceptance = 'Elfogadva' and not exists (select 1 from public.finance_mappings mapping where mapping.project_id = workflow.project_id and mapping.workflow_id = workflow.id)
        union all select 'review:schedule-row:' || review.id, 2, project.id, project.name, review.review_reason, null::date, 'Ütemterv', 'schedules'
        from public.schedule_rows_financial_phase_review review join visible_projects project on project.id = review.project_id
        union all select 'review:subcontractor-key:' || review.workflow_id, 2, project.id, project.name, review.review_reason || ': ' || review.company_name, null::date, 'Alvállalkozók', 'subcontractors'
        from public.subcontractor_workflow_schedule_key_review review join visible_projects project on project.id = review.project_id
        union all select notification.payload ->> 'alert_key', 2, (notification.payload ->> 'project_id')::bigint, notification.payload ->> 'project_name', notification.payload ->> 'message', null::date,
                         case notification.payload ->> 'alert_type' when 'eng' then 'Engedélyek' when 'sub' then 'Alvállalkozók' else 'Értesítések' end,
                         case notification.payload ->> 'alert_type' when 'eng' then 'engagements' when 'sub' then 'subcontractors' else 'disciplines' end
        from public.current_notifications() as notification(payload)
