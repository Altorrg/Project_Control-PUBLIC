begin;

create table if not exists public.workflow_documents (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.projects(id) on delete cascade,
    workflow_id bigint not null references public.subcontractor_workflows(id) on delete cascade,
    document_type text not null check (document_type in (
        'offer_request', 'offer_response', 'contract_draft', 'reference_certificate'
    )),
    revision_no integer not null default 1 check (revision_no >= 1),
    template_version integer not null default 1,
    title text not null default '',
    status text not null default 'draft' check (status in ('draft', 'issued', 'superseded', 'archived')),
    data jsonb not null default '{}'::jsonb,
    issued_at timestamptz,
    issued_by uuid references public.profiles(id) on delete set null,
    created_by uuid references public.profiles(id) on delete set null default auth.uid(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(workflow_id, document_type, revision_no)
);

create index if not exists workflow_documents_project_workflow_idx
    on public.workflow_documents(project_id, workflow_id, document_type, revision_no desc);

alter table public.workflow_documents enable row level security;

grant select, insert, update, delete
    on table public.workflow_documents
    to authenticated;
revoke all
    on table public.workflow_documents
    from anon;

do $document_sequence_grants$
declare
    identity_sequence regclass;
begin
    identity_sequence := pg_get_serial_sequence(
        'public.workflow_documents',
        'id'
    )::regclass;
    if identity_sequence is not null then
        execute format(
            'grant usage, select on sequence %s to authenticated',
            identity_sequence
        );
        execute format(
            'revoke all on sequence %s from anon',
            identity_sequence
        );
    end if;
end;
$document_sequence_grants$;

drop policy if exists workflow_documents_read on public.workflow_documents;
create policy workflow_documents_read on public.workflow_documents for select to authenticated
    using (public.can_access_project(project_id, false));

drop policy if exists workflow_documents_write on public.workflow_documents;
create policy workflow_documents_write on public.workflow_documents for all to authenticated
    using (public.can_access_project(project_id, true))
    with check (public.can_access_project(project_id, true));

drop trigger if exists set_updated_at on public.workflow_documents;
create trigger set_updated_at before update on public.workflow_documents
    for each row execute function public.set_updated_at();

drop trigger if exists audit_changes on public.workflow_documents;
create trigger audit_changes after insert or update or delete on public.workflow_documents
    for each row execute function public.write_audit_log();

commit;
