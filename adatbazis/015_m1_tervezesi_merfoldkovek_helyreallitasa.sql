$preflight$;

-- A fájl a 014-es migráció részleges vagy elmaradt futása esetén is
-- létrehozza a jelen feladathoz szükséges jelkulcssémát.
create table if not exists public.schedule_keys (
    id bigint generated by default as identity primary key,
    code text not null check (char_length(btrim(code)) between 1 and 255),
    code_key text generated always as (lower(btrim(code))) stored unique,
    description text not null default '' check (char_length(description) <= 5000),
    start_event text not null default '' check (char_length(start_event) <= 1000),
    end_event text not null default '' check (char_length(end_event) <= 1000),
    note text not null default '' check (char_length(note) <= 5000),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists schedule_keys_active_code_idx
    on public.schedule_keys(is_active, code, id);

alter table public.schedule_keys enable row level security;
grant select, insert, update, delete on public.schedule_keys to authenticated;
revoke all on public.schedule_keys from anon;

do $sequence_grants$
declare
    sequence_name regclass;
begin
    sequence_name := pg_get_serial_sequence('public.schedule_keys', 'id')::regclass;
    if sequence_name is not null then
        execute format('grant usage, select on sequence %s to authenticated', sequence_name);
        execute format('revoke all on sequence %s from anon', sequence_name);
    end if;
end;
$sequence_grants$;

drop policy if exists schedule_keys_read on public.schedule_keys;
create policy schedule_keys_read
    on public.schedule_keys for select to authenticated
    using (true);

drop policy if exists schedule_keys_write on public.schedule_keys;
create policy schedule_keys_write
    on public.schedule_keys for all to authenticated
    using (public.has_permission('master_data_admin'))
    with check (public.has_permission('master_data_admin'));

drop trigger if exists set_updated_at on public.schedule_keys;
create trigger set_updated_at
    before update on public.schedule_keys
    for each row execute function public.set_updated_at();

drop trigger if exists audit_changes on public.schedule_keys;
create trigger audit_changes
    after insert or update or delete on public.schedule_keys
    for each row execute function public.write_audit_log();

alter table public.schedule_rows
    add column if not exists section text,
    add column if not exists phase_code text,
    add column if not exists financial_phase_no integer,
    add column if not exists schedule_key_id bigint;

do $schedule_constraints$
begin
    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.schedule_rows'::regclass
          and conname = 'schedule_rows_financial_phase_no_check'
    ) then
        alter table public.schedule_rows
            add constraint schedule_rows_financial_phase_no_check
            check (financial_phase_no between 0 and 5);
    end if;

    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.schedule_rows'::regclass
          and conname = 'schedule_rows_project_financial_phase_fkey'
    ) then
        alter table public.schedule_rows
            add constraint schedule_rows_project_financial_phase_fkey
            foreign key (project_id, financial_phase_no)
            references public.project_contract_sections(project_id, section_no)
            on delete restrict;
    end if;

    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.schedule_rows'::regclass
          and conname = 'schedule_rows_schedule_key_id_fkey'
    ) then
        alter table public.schedule_rows
            add constraint schedule_rows_schedule_key_id_fkey
            foreign key (schedule_key_id)
            references public.schedule_keys(id)
            on delete restrict;
    end if;
end;
$schedule_constraints$;

create index if not exists schedule_rows_project_financial_phase_position_idx
    on public.schedule_rows(project_id, financial_phase_no, position, id);
create index if not exists schedule_rows_schedule_key_idx
    on public.schedule_rows(schedule_key_id);

