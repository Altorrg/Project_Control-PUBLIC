-- A Supabase SQL Editorben ennek 30 jelkulcsot és az M1-nél 13 ütemtervi
-- elemet kell mutatnia. Ha itt jó az eredmény, de az alkalmazásban nem,
-- akkor a helyi .env másik Supabase projektre mutat.
select
    to_regclass('public.schedule_keys') is not null as schedule_keys_table_exists,
    (select count(*) from public.schedule_keys where is_active) as active_schedule_key_count,
    (
        select count(*)
        from public.schedule_rows row
        join public.projects project on project.id = row.project_id
        where btrim(project.name) = 'M1'
    ) as m1_schedule_row_count,
    (
        select count(*)
        from public.schedule_rows row
        join public.projects project on project.id = row.project_id
        where btrim(project.name) = 'M1'
          and row.schedule_key_id is null
    ) as m1_unassigned_planning_milestone_count;
